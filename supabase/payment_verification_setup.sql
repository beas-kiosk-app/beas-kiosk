-- BEA'S KIOSK payment verification
-- Run once in Supabase SQL Editor. Uses the existing orders table and is_kiosk_owner() helper.
create table if not exists public.payment_settings (
  id integer primary key default 1 check (id = 1),
  bank_name text, account_name text, account_number text, account_address text,
  transfer_note text default 'If paying to Atlantic Bank, your transfer must be immediate.',
  updated_at timestamptz not null default now()
);
insert into public.payment_settings (id) values (1) on conflict (id) do nothing;
alter table public.payment_settings enable row level security;
drop policy if exists "Owners can view payment settings" on public.payment_settings;
create policy "Owners can view payment settings" on public.payment_settings for select to authenticated using (public.is_kiosk_owner());
drop policy if exists "Owners can update payment settings" on public.payment_settings;
create policy "Owners can update payment settings" on public.payment_settings for update to authenticated using (public.is_kiosk_owner()) with check (public.is_kiosk_owner());
grant select, update on public.payment_settings to authenticated;

create table if not exists public.payment_submissions (
  id bigint generated by default as identity primary key,
  order_number text not null unique, customer_phone text not null, receipt_path text not null,
  status text not null default 'pending' check (status in ('pending','verified','rejected')),
  rejection_reason text, submitted_at timestamptz not null default now(),
  reviewed_at timestamptz, updated_at timestamptz not null default now()
);
alter table public.payment_submissions enable row level security;
drop policy if exists "Owners can view payment submissions" on public.payment_submissions;
create policy "Owners can view payment submissions" on public.payment_submissions for select to authenticated using (public.is_kiosk_owner());
drop policy if exists "Owners can update payment submissions" on public.payment_submissions;
create policy "Owners can update payment submissions" on public.payment_submissions for update to authenticated using (public.is_kiosk_owner()) with check (public.is_kiosk_owner());
grant select, update on public.payment_submissions to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('payment-receipts', 'payment-receipts', false, 5242880, array['image/jpeg','image/png','image/webp','application/pdf'])
on conflict (id) do update set public = false, file_size_limit = 5242880, allowed_mime_types = excluded.allowed_mime_types;
drop policy if exists "Customers can upload payment receipts" on storage.objects;
create policy "Customers can upload payment receipts" on storage.objects for insert to anon, authenticated
with check (bucket_id = 'payment-receipts' and (storage.foldername(name))[1] = 'receipts');
drop policy if exists "Owners can view payment receipts" on storage.objects;
create policy "Owners can view payment receipts" on storage.objects for select to authenticated
using (bucket_id = 'payment-receipts' and public.is_kiosk_owner());

create or replace function public.submit_payment_proof(p_order_number text, p_customer_phone text, p_receipt_path text)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare matched_order public.orders%rowtype;
begin
  if p_order_number is null or p_customer_phone is null or p_receipt_path is null or p_receipt_path not like 'receipts/%' then
    raise exception 'INVALID_PAYMENT_PROOF_DETAILS';
  end if;
  select * into matched_order from public.orders
  where upper(order_number) = upper(trim(p_order_number))
    and regexp_replace(coalesce(customer_phone,''), '[^0-9]', '', 'g') = regexp_replace(trim(p_customer_phone), '[^0-9]', '', 'g')
  limit 1;
  if not found then raise exception 'ORDER_DETAILS_NOT_MATCHED'; end if;
  if lower(coalesce(matched_order.payment_method,'')) not like '%mobile%'
     and lower(coalesce(matched_order.payment_method,'')) not like '%digital%' then
    raise exception 'ORDER_NOT_ELECTRONIC_PAYMENT';
  end if;
  insert into public.payment_submissions(order_number,customer_phone,receipt_path,status,rejection_reason,submitted_at,reviewed_at,updated_at)
  values(matched_order.order_number,matched_order.customer_phone,p_receipt_path,'pending',null,now(),null,now())
  on conflict(order_number) do update set customer_phone=excluded.customer_phone,receipt_path=excluded.receipt_path,status='pending',rejection_reason=null,submitted_at=now(),reviewed_at=null,updated_at=now();
  return jsonb_build_object('status','pending');
end;
$$;
revoke all on function public.submit_payment_proof(text,text,text) from public;
grant execute on function public.submit_payment_proof(text,text,text) to anon, authenticated;

create or replace function public.get_customer_payment_status(p_order_number text)
returns jsonb language sql security definer set search_path = public, pg_temp as $$
  select jsonb_build_object('status',coalesce(ps.status,'not_submitted'),'rejection_reason',ps.rejection_reason)
  from public.orders o left join public.payment_submissions ps on ps.order_number=o.order_number
  where upper(o.order_number)=upper(trim(p_order_number)) limit 1;
$$;
revoke all on function public.get_customer_payment_status(text) from public;
grant execute on function public.get_customer_payment_status(text) to anon, authenticated;
create index if not exists payment_submissions_status_date_idx on public.payment_submissions(status,submitted_at desc);
