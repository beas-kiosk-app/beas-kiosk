-- BEA'S KIOSK inventory tables
-- Run this once in Supabase SQL Editor as the project owner.

create table if not exists public.inventory_items (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Other',
  quantity numeric(12,2) not null default 0 check (quantity >= 0),
  unit text not null default 'units',
  low_stock_threshold numeric(12,2) not null default 0 check (low_stock_threshold >= 0),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  inventory_item_id bigint references public.inventory_items(id) on delete set null,
  item_name text not null,
  movement_type text not null check (movement_type in ('opening', 'restock', 'usage', 'adjustment')),
  quantity_change numeric(12,2) not null,
  quantity_after numeric(12,2) not null check (quantity_after >= 0),
  note text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);

alter table public.inventory_items enable row level security;
alter table public.inventory_movements enable row level security;

drop policy if exists "Owners can view inventory items" on public.inventory_items;
create policy "Owners can view inventory items"
on public.inventory_items for select to authenticated
using (public.is_kiosk_owner());

drop policy if exists "Owners can add inventory items" on public.inventory_items;
create policy "Owners can add inventory items"
on public.inventory_items for insert to authenticated
with check (public.is_kiosk_owner());

drop policy if exists "Owners can update inventory items" on public.inventory_items;
create policy "Owners can update inventory items"
on public.inventory_items for update to authenticated
using (public.is_kiosk_owner()) with check (public.is_kiosk_owner());

drop policy if exists "Owners can delete inventory items" on public.inventory_items;
create policy "Owners can delete inventory items"
on public.inventory_items for delete to authenticated
using (public.is_kiosk_owner());

drop policy if exists "Owners can view inventory movements" on public.inventory_movements;
create policy "Owners can view inventory movements"
on public.inventory_movements for select to authenticated
using (public.is_kiosk_owner());

drop policy if exists "Owners can add inventory movements" on public.inventory_movements;
create policy "Owners can add inventory movements"
on public.inventory_movements for insert to authenticated
with check (public.is_kiosk_owner());

create index if not exists inventory_movements_created_at_idx
on public.inventory_movements (created_at desc);
create index if not exists inventory_movements_item_id_idx
on public.inventory_movements (inventory_item_id);
