-- BEA'S KIOSK expenses and profit tracking
-- Run once in Supabase SQL Editor as the project owner.

create table if not exists public.business_expenses (
  id bigint generated by default as identity primary key,
  description text not null,
  category text not null default 'Other',
  amount numeric(12,2) not null check (amount > 0),
  expense_date date not null default current_date,
  vendor text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.business_expenses enable row level security;

drop policy if exists "Owners can view business expenses" on public.business_expenses;
create policy "Owners can view business expenses"
on public.business_expenses for select to authenticated
using (public.is_kiosk_owner());

drop policy if exists "Owners can add business expenses" on public.business_expenses;
create policy "Owners can add business expenses"
on public.business_expenses for insert to authenticated
with check (public.is_kiosk_owner());

drop policy if exists "Owners can update business expenses" on public.business_expenses;
create policy "Owners can update business expenses"
on public.business_expenses for update to authenticated
using (public.is_kiosk_owner()) with check (public.is_kiosk_owner());

drop policy if exists "Owners can delete business expenses" on public.business_expenses;
create policy "Owners can delete business expenses"
on public.business_expenses for delete to authenticated
using (public.is_kiosk_owner());

grant select, insert, update, delete
on table public.business_expenses to authenticated;

do $$
declare
  expense_seq text;
begin
  expense_seq := pg_get_serial_sequence('public.business_expenses', 'id');
  if expense_seq is not null then
    execute format('grant usage, select on sequence %s to authenticated', expense_seq);
  end if;
end $$;

create index if not exists business_expenses_date_idx
on public.business_expenses (expense_date desc);
